"""
Fills every "[LIVE RUN]" placeholder in EVIDENCE.md with the matching section of
reports/evidence_run.md (written by scripts/collect_evidence.py). Re-runnable
only on a fresh EVIDENCE.md template: it refuses to run if no placeholders remain.

Usage:  python scripts/collect_evidence.py && python scripts/fill_evidence.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
run_path = os.path.join(ROOT, "reports", "evidence_run.md")
ev_path = os.path.join(ROOT, "EVIDENCE.md")

if not os.path.exists(run_path):
    sys.exit("reports/evidence_run.md not found - run scripts/collect_evidence.py first")

run = open(run_path, encoding="utf-8").read()
# split into "### title" sections
parts = re.split(r"(?m)^### ", run)[1:]
sections = [("### " + p.rstrip() + "\n") for p in parts]


def pick(*prefixes):
    out = [s for s in sections if any(s[4:].startswith(p) for p in prefixes)]
    if not out:
        sys.exit(f"No section starting with {prefixes} in evidence_run.md")
    return "\n".join(s.replace("### ", "#### ", 1) for s in out)


text = open(ev_path, encoding="utf-8").read()
if "[LIVE RUN]" not in text:
    sys.exit("EVIDENCE.md has no [LIVE RUN] placeholders left - nothing to do")

text = text.replace("Sections marked **[LIVE RUN]** are filled", "Sections headed 'Live run output' are filled")

RULES = [  # (substring identifying the placeholder line, replacement builder)
    ("paste Probe 1 output", lambda: pick("Probe 1")),
    ("paste `GET /jobs` output", lambda: "The `GET /jobs` output is part of the Probe 1 block above."),
    ("paste Probe 6", lambda: pick("Probe 6")),
    ("paste Probe 2", lambda: pick("Probe 2")),
    ("the real-embedding evidence is the", lambda: "The real-embedding evidence is the \"Vulpes vulpes\" / \"Canis lupus\" rows of the Probe 5 eval output further down (concept posts)."),
    ("paste Probe 3 / 3b", lambda: pick("Probe 3")),
    ("paste Probe 4", lambda: pick("Probe 4")),
    ("paste the review-workflow transcript", lambda: pick("Review workflow")),
    ("paste Probe 5", lambda: pick("Probe 5")),
]

lines, out = text.split("\n"), []
for line in lines:
    if "[LIVE RUN]" in line:
        for key, build in RULES:
            if key in line:
                prefix = line.split("**[LIVE RUN]**")[0].rstrip()
                if prefix:
                    out.append(prefix)
                out.append("")
                out.append("**Live run output** (generated by `scripts/collect_evidence.py`):")
                out.append("")
                out.append(build())
                break
        else:
            sys.exit(f"Unrecognised placeholder line: {line[:100]}")
    else:
        out.append(line)

final = "\n".join(out)
if "[LIVE RUN]" in final:
    sys.exit("Some placeholders were not replaced")
open(ev_path, "w", encoding="utf-8").write(final)
print(f"EVIDENCE.md updated ({len(final.splitlines())} lines). Open it and skim every section.")